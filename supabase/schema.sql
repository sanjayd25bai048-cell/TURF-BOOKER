-- Supabase schema for hosted deployments. Enable Realtime for slot_locks and bookings
-- in Database > Publications. Keep service-role credentials on the FastAPI server only.
create extension if not exists pgcrypto;

create table if not exists public.venues (
  id bigint generated by default as identity primary key,
  name text not null,
  address text not null,
  description text not null default '',
  active boolean not null default true
);
create table if not exists public.courts (
  id bigint generated by default as identity primary key,
  venue_id bigint not null references public.venues(id),
  name text not null,
  sport text not null,
  surface text not null,
  hourly_base integer not null check (hourly_base > 0),
  active boolean not null default true
);
create table if not exists public.slot_locks (
  id bigint generated by default as identity primary key,
  court_id bigint not null references public.courts(id),
  slot_date date not null,
  start_time time not null,
  end_time time not null,
  token uuid not null unique default gen_random_uuid(),
  user_name text not null,
  expires_at timestamptz not null,
  created_at timestamptz not null default now(),
  constraint one_live_lock_per_slot unique(court_id,slot_date,start_time)
);
create table if not exists public.bookings (
  id text primary key,
  court_id bigint not null references public.courts(id),
  slot_date date not null,
  start_time time not null,
  end_time time not null,
  customer_name text not null,
  phone text not null,
  amount integer not null check (amount >= 0),
  status text not null default 'confirmed',
  created_at timestamptz not null default now(),
  constraint one_booking_per_slot unique(court_id,slot_date,start_time)
);
create table if not exists public.payments (
  id text primary key,
  booking_id text not null references public.bookings(id),
  amount integer not null,
  method text not null,
  status text not null,
  created_at timestamptz not null default now()
);
create index if not exists slot_locks_expiry_idx on public.slot_locks(expires_at);
create index if not exists bookings_date_idx on public.bookings(slot_date,court_id);

alter table public.venues enable row level security;
alter table public.courts enable row level security;
alter table public.slot_locks enable row level security;
alter table public.bookings enable row level security;
alter table public.payments enable row level security;

drop policy if exists "Public can read active venues" on public.venues;
create policy "Public can read active venues" on public.venues for select using (active = true);
drop policy if exists "Public can read active courts" on public.courts;
create policy "Public can read active courts" on public.courts for select using (active = true);
-- Do not expose customer bookings, payments, or slot lock tokens to anonymous clients.
-- FastAPI should use the Supabase service-role key for writes and private reads.
